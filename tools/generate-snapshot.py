#!/usr/bin/env python3
"""Generate a Solidity offline test fixture from recorded, pinned fork RPC reads.

Only actual nonempty runtime code and original storage words are installed. This
is a partial replay of the accessed state, not a full chain snapshot or a mock.
No filesystem cheatcodes or RPC calls are needed by the resulting Solidity test.
"""
import argparse
import hashlib
import json
from pathlib import Path

BLOCK = 12019224
CHAIN = 11155111


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('recording', type=Path)
    parser.add_argument('--output', type=Path, default=Path('test/fixtures/GraphASnapshot.sol'))
    parser.add_argument('--metadata', type=Path, default=Path('test/fixtures/graph-a-snapshot.json'))
    args = parser.parse_args()
    records = json.loads(args.recording.read_text())
    blocks, codes, slots = [], {}, {}
    for key, response in records.items():
        method, params = json.loads(key)
        result = response['result']
        if method == 'eth_getBlockByNumber' and params[0] == hex(BLOCK):
            blocks.append(result)
        if method == 'eth_getCode' and result != '0x':
            # Exclude the chain's unrelated deterministic deployment helper.
            if params[0].lower() == '0x4e59b44847b379578588920ca78fbf26c0b4956c':
                continue
            codes[params[0].lower()] = result
        if method == 'eth_getStorageAt':
            if params[0].lower() == '0x7109709ecfa91a80626ff3989d68f67f5b1dd12d':
                continue  # Foundry's synthetic cheatcode account, not a graph contract.
            slot = f'0x{int(params[1], 16):064x}'
            slots[(params[0].lower(), slot)] = f'0x{int(result, 16):064x}'
    if len(blocks) != 1 or int(blocks[0]['number'], 16) != BLOCK:
        raise SystemExit('recording must contain exactly the requested block')
    block = blocks[0]
    # EIP-1898 fork reads must be tied to this block hash; no latest-state mixing.
    for key in records:
        method, params = json.loads(key)
        if method in ('eth_getStorageAt', 'eth_getCode'):
            if method == 'eth_getCode' and params[0].lower() == '0x4e59b44847b379578588920ca78fbf26c0b4956c':
                continue
            tag = params[-1]
            if tag not in (hex(BLOCK), block['hash'], {'blockHash': block['hash']}, {'blockHash': block['hash'], 'requireCanonical': False}):
                raise SystemExit(f'unpinned state: {key}')
    data = {
        'chainId': CHAIN,
        'blockNumber': BLOCK,
        'blockHash': block['hash'],
        'stateRoot': block['stateRoot'],
        'timestamp': int(block['timestamp'], 16),
        'scope': 'Original runtime bytes and only storage slots read by GraphAAssertions at this block. Not a complete state snapshot or a state-root proof.',
        'source': 'https://sepolia.rpc.sentio.xyz',
        'contracts': [
            {'address': addr, 'runtimeBytes': len(code[2:]) // 2,
             'runtimeSha256': hashlib.sha256(bytes.fromhex(code[2:])).hexdigest(),
             'storageSlots': sum(a == addr for a, _ in slots)}
            for addr, code in sorted(codes.items())
        ],
    }
    lines = [
        '// SPDX-License-Identifier: MIT', 'pragma solidity 0.8.26;', '',
        'import {Vm} from "forge-std/Vm.sol";', '',
        '/// @dev Generated by tools/generate-snapshot.py. Original Sepolia code and accessed storage only.',
        '/// Not a production dependency, complete state snapshot, or replacement for the live fork run.',
        'library GraphASnapshot {',
        f'    bytes32 internal constant BLOCK_HASH = {block["hash"]};',
        '    function load(Vm vm) internal {',
        f'        vm.chainId({CHAIN});', f'        vm.roll({BLOCK});',
        f'        vm.warp({int(block["timestamp"], 16)});',
    ]
    for addr, code in sorted(codes.items()):
        # bytes20 conversion avoids case/checksum ambiguity in generated source.
        lines.append(f'        vm.etch(address(bytes20(hex"{addr[2:]}")), hex"{code[2:]}");')
    for (addr, slot), value in sorted(slots.items()):
        if addr not in codes:
            raise SystemExit(f'storage without recorded runtime: {addr}')
        lines.append(f'        vm.store(address(bytes20(hex"{addr[2:]}")), {slot}, {value});')
    lines += ['    }', '}', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines))
    args.metadata.write_text(json.dumps(data, indent=2) + '\n')
    print(f'Wrote {len(codes)} contracts, {len(slots)} storage slots at block {BLOCK}')


if __name__ == '__main__':
    main()
